# code_builder.py
import os
import re
import json


class StagedCodeBuilder:
    """Handles parsing Ruby's JSON plan, creating the target Python file,
    formatting stage prompts, and appending generated code stage-by-stage.
    """

    def parse_plan(self, agent_reply):
        """Extracts the JSON dictionary from between :-start-: markers."""
        start_marker = ":-start-:"
        start = agent_reply.index(start_marker) + len(start_marker)
        end = agent_reply.index(start_marker, start)
        json_string = agent_reply[start:end].strip()

        plan_data = json.loads(json_string)
        target_file = plan_data.pop("file_name", "generated_script.py")
        return target_file, plan_data

    def create_target_file(self, target_file):
        """Creates/resets the target Python file before Stage 1 begins."""
        with open(target_file, "w", encoding="utf-8") as f:
            f.write("# Auto-generated by Ruby & Qwen_coder\n")
        print(f">>> Ruby created target file: {os.path.abspath(target_file)}")

    def build_stage_prompt(self, stage_name, stage_data, is_first_stage, is_final_stage):
        """Builds the prompt for Qwen_coder so it only generates new code for the current stage."""
        raw_instructions = stage_data["prompt"]

        if not is_final_stage:
            raw_instructions = re.sub(
                r",?\s*followed by an `if __name__ == '__main__':`.*?\.",
                ".",
                raw_instructions,
                flags=re.IGNORECASE,
            )

        if is_first_stage:
            return (
                f"Execute {stage_name}: {stage_data['plan']}\n"
                f"Instructions: {raw_instructions}\n"
                f"RULES:\n"
                f"1. Write ONLY the imports, class definition, `__init__`, and methods for {stage_name}.\n"
                f"2. Do NOT add comments like `# Output ends here`.\n"
                f"3. Output valid Python inside a single ```python code block."
            )

        if is_final_stage:
            return (
                f"Now execute the FINAL_STAGE ({stage_name}): {stage_data['plan']}\n"
                f"Instructions: {raw_instructions}\n\n"
                f"CRITICAL APPEND RULES:\n"
                f"1. Write ONLY the new class methods for {stage_name} indented by 4 spaces. Do NOT repeat previous methods.\n"
                f"2. Output inside a single ```python code block."
            )

        return (
            f"Now execute {stage_name}: {stage_data['plan']}\n"
            f"Instructions: {raw_instructions}\n\n"
            f"CRITICAL APPEND RULES:\n"
            f"1. Write ONLY the new methods for {stage_name}. Do NOT repeat imports, the `class` line, `__init__`, or any methods from previous stages.\n"
            f"2. Indent new class methods by 4 spaces so they can be appended directly inside the existing class.\n"
            f"3. Do NOT include `if __name__ == '__main__':`, `# Output ends here`, or `:-done-:`.\n"
            f"4. Output inside a single ```python code block."
        )

    def extract_and_format_code(self, raw_reply, is_first_stage):
        """Extracts Python code from markdown fences and ensures proper indentation for appending."""
        code_match = re.search(r"```(?:python)?\s*\n(.*?)```", raw_reply, re.DOTALL)
        if code_match:
            code = code_match.group(1)
        else:
            code = raw_reply.replace(":-done-:", "")

        # Remove trailing filler comments like `# Output ends here`
        lines = [
            line for line in code.rstrip().splitlines()
            if not re.match(r"^\s*#\s*output ends here.*$", line, re.IGNORECASE)
        ]
        while lines and not lines[-1].strip():
            lines.pop()

        if not lines:
            return ""

        if is_first_stage:
            return "\n".join(lines) + "\n"

        # Stage 2+: Strip accidental duplicate imports or `class ClassName:` lines
        cleaned_lines = []
        skip_header = True
        for line in lines:
            stripped = line.strip()
            if skip_header:
                if stripped.startswith(("from ", "import ")):
                    continue
                if re.match(r"^class\s+\w+.*:$", stripped):
                    continue
                if stripped == "":
                    continue
                skip_header = False
            cleaned_lines.append(line)

        if not cleaned_lines:
            return ""

        # Separate class methods from any `if __name__ == '__main__':` block
        method_lines = []
        main_lines = []
        in_main = False

        for line in cleaned_lines:
            if re.match(r"^if\s+__name__\s*==\s*['\"]__main__['\"]\s*:", line.strip()):
                in_main = True
            if in_main:
                main_lines.append(line)
            else:
                method_lines.append(line)

        formatted_chunks = []

        if method_lines:
            first_non_empty = next((l for l in method_lines if l.strip()), "")
            if not first_non_empty.startswith((" ", "\t")):
                method_lines = [("    " + l if l.strip() else "") for l in method_lines]
            formatted_chunks.append("\n".join(method_lines))

        if main_lines:
            first_main = main_lines[0]
            leading_spaces = len(first_main) - len(first_main.lstrip())
            if leading_spaces > 0:
                main_lines = [
                    l[leading_spaces:] if len(l) >= leading_spaces else l
                    for l in main_lines
                ]
            formatted_chunks.append("\n" + "\n".join(main_lines))

        return "\n".join(formatted_chunks) + "\n"

    def append_to_file(self, target_file, code_chunk):
        """Appends the formatted code chunk to the target Python file."""
        with open(target_file, "a", encoding="utf-8") as f:
            f.write("\n" + code_chunk)

    def execute_stages(self, agent_reply, coder_instance):
        """Runs the complete multi-stage generation and file-appending workflow."""
        target_file, stages = self.parse_plan(agent_reply)
        self.create_target_file(target_file)

        total_stages = len(stages)
        last_coder_reply = ""

        for idx, (stage_name, stage_data) in enumerate(stages.items()):
            is_first_stage = (idx == 0)
            is_final_stage = (idx == total_stages - 1)

            if is_final_stage:
                stage_data["stage_type"] = "FINAL_STAGE"
            else:
                stage_data.pop("stage_type", None)

            print("\n" + "-" * 50)
            print(f"Executing: {stage_name} ({idx + 1}/{total_stages}) -> Appending to {target_file}")
            print("-" * 50)
            print(stage_data)
            print("-" * 50)

            stage_prompt = self.build_stage_prompt(
                stage_name, stage_data, is_first_stage, is_final_stage
            )
            last_coder_reply = coder_instance.ccode(stage_prompt)

            new_code_chunk = self.extract_and_format_code(
                last_coder_reply, is_first_stage=is_first_stage
            )
            self.append_to_file(target_file, new_code_chunk)
            print(f">>> Successfully appended {stage_name} to '{target_file}'.")

        # AUTOMATIC FALLBACK: Check if the final file contains an `__main__` block.
        # If the 3B coder omitted it, append a clean test block automatically.
        with open(target_file, "r", encoding="utf-8") as f:
            file_content = f.read()

        if "__main__" not in file_content:
            print("\n>>> Notice: Coder omitted the main test block. Automatically appending fallback test block...")
            fallback_main = (
                "\n\nif __name__ == '__main__':\n"
                "    cal = Calendar()\n"
                "    cal.add_event('2026-10-18', 'Team Meeting')\n"
                "    cal.add_event('2026-10-19', 'Project Deadline')\n"
                "    print('Events on 2026-10-18:', cal.list_events('2026-10-18'))\n"
                "    \n"
                "    cal.add_event_to_calendar('Work', '2026-10-18', 'Code Review')\n"
                "    print('Exporting calendar...')\n"
                "    cal.export_calendar('calendar_export.txt')\n"
                "    print('Done!')\n"
            )
            with open(target_file, "a", encoding="utf-8") as f:
                f.write(fallback_main)
            print(">>> Fallback test block successfully appended.")

        print(f"\n>>> All stages complete. Full script saved to '{target_file}'.")
        return last_coder_reply